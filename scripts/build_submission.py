"""Build agents/main.py from the best genome found so far, then validate it.

The submission is a single stdlib-only file: opt/policy.py inlined, the genome
embedded as a literal, and a hard try/except so a bug degrades to PASS instead
of erroring the episode (an errored agent forfeits).

    python scripts/build_submission.py [checkpoint.json ...]
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "agents" / "main.py"

HEADER = '''"""Kaggriculture agent -- generated by scripts/build_submission.py. Do not edit.

Policy: priority scheduler over a searched economics genome.
Genome fitness at build time: {fitness}  (mean final money vs `starter`, island {island} gen {gen})
Built: {when}
"""
'''

FOOTER = '''

# ----------------------------------------------------------------- submission
GENOME = {genome!r}

_impl = make_agent(GENOME)
_PASS = {{"farmer": ["PASS"], "hands": [], "market": []}}


def agent(observation, configuration=None):
    """Entry point. Never raises: an agent that errors forfeits the episode, and
    a PASS turn costs far less than a crash."""
    try:
        return _impl(observation)
    except Exception:
        return _PASS
'''


def best_genome(paths: list[Path]):
    best = None
    for p in paths:
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        cands = []
        if d.get("best"):
            cands.append((d.get("best_fitness", 0), d["best"], d.get("island", p.stem), d.get("gen", 0)))
        for g in d.get("pool", []):
            if g.get("genome"):
                cands.append((g.get("fitness", 0), g["genome"], g.get("island", p.stem), 0))
        for c in cands:
            if best is None or c[0] > best[0]:
                best = c
    return best


def build(fitness, genome, island, gen) -> str:
    src = (ROOT / "opt" / "policy.py").read_text(encoding="utf-8")
    # Drop the module docstring (replaced) and the __main__ block (imports fastsim).
    src = src.split('if __name__ == "__main__":')[0]
    src = src.split('"""', 2)[2] if src.startswith('"""') else src
    body = HEADER.format(fitness=format(int(fitness), ","), island=island, gen=gen,
                         when=time.strftime("%Y-%m-%d %H:%M")) + src
    body += FOOTER.format(genome=[round(float(v), 6) for v in genome])
    return body


def validate(path: Path) -> bool:
    """Play a real episode in the official runner. This is the only check that counts."""
    sys.path.insert(0, str(ROOT / "engine"))
    from kaggle_environments import make

    spec_src = path.read_text(encoding="utf-8")
    for bad in ("__file__", "import numpy", "import kaggle_environments"):
        if bad in spec_src:
            print(f"FAIL: submission references {bad!r}")
            return False

    timings = []
    ns = {}
    exec(compile(spec_src, str(path), "exec"), ns)
    raw = ns["agent"]

    def timed(obs, config=None):
        t = time.time()
        a = raw(obs, config)
        timings.append(time.time() - t)
        return a

    env = make("kaggriculture", configuration={"episodeSteps": 720, "seed": 4242}, debug=True)
    env.run([timed, "starter"])
    last = env.steps[-1]
    statuses = [s.status for s in last]
    rewards = [s.reward for s in last]
    worst = max(timings) * 1000
    mean = sum(timings) / len(timings) * 1000
    print(f"official runner: {len(env.steps)} steps, status={statuses}, reward={rewards}")
    print(f"latency: mean {mean:.2f} ms, worst {worst:.0f} ms over {len(timings)} calls")
    ok = len(env.steps) == 720 and all(s == "DONE" for s in statuses) and worst < 200
    if not ok:
        print("FAIL: expected 720 steps, DONE/DONE, worst-case < 200 ms")
    return ok


def main() -> int:
    paths = [Path(a) for a in sys.argv[1:]] or [ROOT / "runs" / "best.json", ROOT / "runs" / "local.json"]
    got = best_genome(paths)
    if not got:
        print("no genome found in", [str(p) for p in paths])
        return 1
    fitness, genome, island, gen = got
    print(f"best genome: fitness {format(int(fitness), ',')} from {island} gen {gen}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(fitness, genome, island, gen), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)")
    return 0 if validate(OUT) else 1


if __name__ == "__main__":
    raise SystemExit(main())
